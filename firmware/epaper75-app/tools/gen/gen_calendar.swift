// Generates include/cal/CalendarData.h: lunar month starts (from Foundation's
// ICU Chinese calendar) and the 24 solar terms (Meeus ch. 25 apparent solar
// longitude, ~15 min accuracy) as Beijing-time dates.
//
//   swift tools/gen/gen_calendar.swift > include/cal/CalendarData.h
//
// Terms whose computed Beijing time falls within 45 minutes of midnight are
// reported on stderr and must be checked against an authoritative almanac.
import Foundation

let firstYear = 2025, lastYear = 2035
let tz = TimeZone(identifier: "Asia/Shanghai")!
var greg = Calendar(identifier: .gregorian); greg.timeZone = tz
var chinese = Calendar(identifier: .chinese); chinese.timeZone = tz

func rad(_ d: Double) -> Double { d * .pi / 180 }
func norm(_ d: Double) -> Double { let r = d.truncatingRemainder(dividingBy: 360); return r < 0 ? r + 360 : r }

func apparentLongitude(_ jde: Double) -> Double {
  let t = (jde - 2451545.0) / 36525.0
  let l0 = 280.46646 + 36000.76983 * t + 0.0003032 * t * t
  let m = 357.52911 + 35999.05029 * t - 0.0001537 * t * t
  let c = (1.914602 - 0.004817 * t - 0.000014 * t * t) * sin(rad(m))
    + (0.019993 - 0.000101 * t) * sin(rad(2 * m)) + 0.000289 * sin(rad(3 * m))
  let omega = 125.04 - 1934.136 * t
  return norm(l0 + c - 0.00569 - 0.00478 * sin(rad(omega)))
}

func julianDay(_ y: Int, _ mo: Int, _ d: Double) -> Double {
  var y = y, m = mo
  if m <= 2 { y -= 1; m += 12 }
  let a = y / 100, b = 2 - a + a / 4
  return Double(Int(365.25 * Double(y + 4716))) + Double(Int(30.6001 * Double(m + 1))) + d + Double(b) - 1524.5
}

func dateFromJD(_ jd: Double) -> (Int, Int, Int, Double) {
  let z = Int(jd + 0.5), f = jd + 0.5 - Double(z)
  let alpha = Int((Double(z) - 1867216.25) / 36524.25)
  let a = z + 1 + alpha - alpha / 4
  let b = a + 1524, c = Int((Double(b) - 122.1) / 365.25)
  let d = Int(365.25 * Double(c)), e = Int(Double(b - d) / 30.6001)
  let day = b - d - Int(30.6001 * Double(e))
  let month = e < 14 ? e - 1 : e - 13
  let year = month > 2 ? c - 4716 : c - 4715
  return (year, month, day, f * 24)
}

// Gregorian-month order: index 0 = 小寒 (285 deg) ... 23 = 冬至 (270 deg).
let termLongitudes = (0..<24).map { norm(285.0 + Double($0) * 15.0) }
let deltaTSeconds = 69.0

var termDays = [[Int]]()
var warnings = [String]()
for year in firstYear...lastYear {
  var row = [Int]()
  for (i, target) in termLongitudes.enumerated() {
    let month = i / 2 + 1
    var jde = julianDay(year, month, i % 2 == 0 ? 6 : 21)
    for _ in 0..<50 {
      var diff = target - apparentLongitude(jde)
      if diff > 180 { diff -= 360 } else if diff < -180 { diff += 360 }
      jde += diff / 360.0 * 365.2422
      if abs(diff) < 1e-7 { break }
    }
    let beijing = jde - deltaTSeconds / 86400.0 + 8.0 / 24.0
    let (y, m, d, hours) = dateFromJD(beijing)
    precondition(y == year && m == month, "term \(i) of \(year) left its month")
    row.append(d)
    let minutes = hours * 60
    if minutes < 45 || minutes > 1440 - 45 {
      warnings.append(String(format: "%d-%02d-%02d term#%d at %02d:%02d Beijing", y, m, d, i, Int(hours), Int(minutes) % 60))
    }
  }
  termDays.append(row)
}

// Lunar month starts from 2024-12-01 through 2036-02-28, days since 2025-01-01.
let epoch = greg.date(from: DateComponents(year: 2025, month: 1, day: 1, hour: 12))!
var day = greg.date(from: DateComponents(year: 2024, month: 12, day: 1, hour: 12))!
let end = greg.date(from: DateComponents(year: 2036, month: 2, day: 28, hour: 12))!
var starts = [(Int, Int, Bool)]()
var first = true
while day <= end {
  let c = chinese.dateComponents([.month, .day, .isLeapMonth], from: day)
  if c.day == 1 || first {
    let offset = greg.dateComponents([.day], from: epoch, to: day).day!
    if c.day == 1 { starts.append((offset - (c.day! - 1), c.month!, c.isLeapMonth!)) }
    else { starts.append((offset - (c.day! - 1), c.month!, c.isLeapMonth!)) }
    first = false
  }
  day = greg.date(byAdding: .day, value: 1, to: day)!
}

for w in warnings { FileHandle.standardError.write((w + "\n").data(using: .utf8)!) }

print("""
