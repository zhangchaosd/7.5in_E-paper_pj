constexpr int kDataLastYear = \(lastYear);

// Day of month for each solar term, in Gregorian-month order:
// [0] 小寒 [1] 大寒 [2] 立春 ... [22] 大雪 [23] 冬至.
constexpr uint8_t kSolarTermDay[\(lastYear - firstYear + 1)][24] = {
""")
for (i, row) in termDays.enumerated() {
  print("    {" + row.map(String.init).joined(separator: ", ") + "},  // \(firstYear + i)")
}
print("""
};

struct LunarMonthStart {
  int16_t dayIndex;  // days since 2025-01-01 (Beijing)
  uint8_t month;     // 1..12
  uint8_t leap;      // 1 = leap month (闰)
};

constexpr LunarMonthStart kLunarMonths[] = {
""")
for (i, s) in starts.enumerated() {
  print("    {\(s.0), \(s.1), \(s.2 ? 1 : 0)}," + (i % 4 == 3 ? "" : ""))
}
print("""
};
constexpr uint16_t kLunarMonthCount = sizeof(kLunarMonths) / sizeof(kLunarMonths[0]);

}  // namespace cal
""")
