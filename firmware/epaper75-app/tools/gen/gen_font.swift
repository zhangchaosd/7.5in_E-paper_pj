// Rasterizes an OpenType font into a 1-bit glyph table for ui::FontData.
//
//   swift tools/gen/gen_font.swift <font.otf> <pixel-size> <symbol> <charset.txt> > out.cpp
//
// charset.txt is UTF-8; every distinct BMP code point in it is emitted (line
// breaks ignored). Glyphs are rendered by CoreText with anti-aliasing and then
// thresholded, which keeps thin CJK strokes better than aliased rendering.
// Missing glyphs are reported on stderr and skipped.
import CoreGraphics
import CoreText
import Foundation

let args = CommandLine.arguments
guard args.count == 5, let pixelSize = Double(args[2]) else {
  FileHandle.standardError.write("usage: gen_font.swift font.otf px symbol charset.txt\n".data(using: .utf8)!)
  exit(2)
}
let fontURL = URL(fileURLWithPath: args[1]) as CFURL
let symbol = args[3]
let charsetText = try! String(contentsOfFile: args[4], encoding: .utf8)

guard let descriptors = CTFontManagerCreateFontDescriptorsFromURL(fontURL) as? [CTFontDescriptor],
      let descriptor = descriptors.first else {
  FileHandle.standardError.write("cannot load font\n".data(using: .utf8)!)
  exit(1)
}
let font = CTFontCreateWithFontDescriptor(descriptor, CGFloat(pixelSize), nil)
let ascent = Int(CTFontGetAscent(font).rounded())
let descent = Int(CTFontGetDescent(font).rounded())

var scalars = Set<UInt16>()
for s in charsetText.unicodeScalars where s.value >= 0x20 && s.value <= 0xFFFF {
  if s.value == 0x0A || s.value == 0x0D { continue }
  scalars.insert(UInt16(s.value))
}
let codes = scalars.sorted()

let canvas = Int(pixelSize * 2.2) + 8
let originX = Int(pixelSize * 0.4) + 2
let baselineFromTop = Int(pixelSize * 1.3) + 2
let threshold: UInt8 = 128  // coverage >= 50% becomes ink

struct Glyph { var code: UInt16; var offset: Int; var w: Int; var h: Int; var xo: Int; var yo: Int; var adv: Int }
var glyphs = [Glyph]()
var bits = [UInt8]()
var bitAccumulator: UInt8 = 0
var bitCount = 0
var missing = [String]()

func pushBit(_ on: Bool) {
  bitAccumulator = (bitAccumulator << 1) | (on ? 1 : 0)
  bitCount += 1
  if bitCount == 8 { bits.append(bitAccumulator); bitAccumulator = 0; bitCount = 0 }
}
func flushBits() {
  if bitCount > 0 { bits.append(bitAccumulator << UInt8(8 - bitCount)); bitAccumulator = 0; bitCount = 0 }
}

let gray = CGColorSpaceCreateDeviceGray()
for code in codes {
  var unichar = code
  var glyph: CGGlyph = 0
  if !CTFontGetGlyphsForCharacters(font, &unichar, &glyph, 1) || (glyph == 0 && code != 0x20) {
    missing.append(String(UnicodeScalar(code)!))
    continue
  }
  var advance = CGSize.zero
  CTFontGetAdvancesForGlyphs(font, .horizontal, &glyph, &advance, 1)

  let ctx = CGContext(data: nil, width: canvas, height: canvas, bitsPerComponent: 8,
                      bytesPerRow: canvas, space: gray, bitmapInfo: CGImageAlphaInfo.none.rawValue)!
  ctx.setFillColor(gray: 1, alpha: 1)
  ctx.fill(CGRect(x: 0, y: 0, width: canvas, height: canvas))
  ctx.setShouldAntialias(true)
  ctx.setShouldSmoothFonts(false)
  ctx.setFillColor(gray: 0, alpha: 1)
  var position = CGPoint(x: CGFloat(originX), y: CGFloat(canvas - baselineFromTop))
  CTFontDrawGlyphs(font, &glyph, &position, 1, ctx)
  let data = ctx.data!.bindMemory(to: UInt8.self, capacity: canvas * canvas)

  // CGContext memory is top-down: row 0 is the top of the image.
  var minX = canvas, minY = canvas, maxX = -1, maxY = -1
  for y in 0..<canvas {
    for x in 0..<canvas where 255 - data[y * canvas + x] >= threshold {
      minX = min(minX, x); maxX = max(maxX, x); minY = min(minY, y); maxY = max(maxY, y)
    }
  }
  let adv = Int(advance.width.rounded())
  if maxX < 0 {
    glyphs.append(Glyph(code: code, offset: bits.count, w: 0, h: 0, xo: 0, yo: 0, adv: adv))
    continue
  }
  let offset = bits.count
  for y in minY...maxY {
    for x in minX...maxX { pushBit(255 - data[y * canvas + x] >= threshold) }
  }
  flushBits()
  glyphs.append(Glyph(code: code, offset: offset, w: maxX - minX + 1, h: maxY - minY + 1,
                      xo: minX - originX, yo: minY - baselineFromTop, adv: adv))
}

if !missing.isEmpty {
  FileHandle.standardError.write("\(symbol): \(missing.count) missing glyphs: \(missing.prefix(40).joined())\n".data(using: .utf8)!)
}
FileHandle.standardError.write("\(symbol): \(glyphs.count) glyphs, \(bits.count) bitmap bytes\n".data(using: .utf8)!)

var out = """
// Generated by tools/gen/gen_font.swift from Noto Sans SC (SIL OFL 1.1).
// Do not edit by hand. Size \(Int(pixelSize)) px, \(glyphs.count) glyphs.
#include "ui/Fonts.h"

namespace ui {
namespace {

const uint16_t kCodes[] = {
"""
for (i, g) in glyphs.enumerated() {
  out += (i % 16 == 0 ? "\n    " : " ") + "0x" + String(g.code, radix: 16) + ","
}
out += "\n};\n\nconst GlyphInfo kGlyphs[] = {"
for (i, g) in glyphs.enumerated() {
  out += (i % 4 == 0 ? "\n    " : " ") + "{\(g.offset), \(g.w), \(g.h), \(g.xo), \(g.yo), \(g.adv)},"
}
out += "\n};\n\nconst uint8_t kBitmap[] = {"
for (i, b) in bits.enumerated() {
  out += (i % 20 == 0 ? "\n    " : "") + String(format: "0x%02x,", b)
}
if bits.isEmpty { out += "0x00" }
out += """

};

}  // namespace

extern const FontData \(symbol) = {kCodes, kGlyphs, kBitmap, \(glyphs.count), \(ascent), \(descent)};

}  // namespace ui

"""
print(out, terminator: "")
